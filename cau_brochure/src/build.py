def add_table(groups):
    rows = ''
    for g, items in groups:
        rows += f'<tr class="g"><td colspan="3">{g}</td></tr>'
        for name, desc, old, new in items:
            rows += f'<tr><td class="n">{name}</td><td class="d">{desc}</td><td class="p">{price(old, new)}</td></tr>'
    return f'<table class="add"><thead><tr><th>Обследование</th><th>Что выявляет</th><th class="p">KRW</th></tr></thead>{rows}</table>'


